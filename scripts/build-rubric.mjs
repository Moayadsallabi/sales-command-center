function buildDimensionsModule(r) {
  const entries = r.dimensions
    .map(
      (d) =>
        `  {\n    key: "${d.key}",\n    name: ${JSON.stringify(d.name)},\n` +
        `    plainName: ${JSON.stringify(d.plainName)},\n` +
        `    plainQuestion: ${JSON.stringify(d.plainQuestion)},\n` +
        `    column: ${JSON.stringify(d.column)},\n` +
        `    question: ${JSON.stringify(d.question)},\n  },`
    )
    .join("\n");

  const verdicts = r.verdicts
    .map((v) => `  { min: ${v.min}, label: ${JSON.stringify(v.label)} },`)
    .join("\n");

  return `// ${GENERATED_BY}

export type DimensionKey =
${r.dimensions.map((d) => `  | "${d.key}"`).join("\n")};

export interface Dimension {
  /** Field name in the scorer's output and on the CallRecord. */
  key: DimensionKey;
  /** Internal name. Matches the Notion column; not shown in the dashboard. */
  name: string;
  /** What the dashboard shows. Readable without knowing the methodology. */
  plainName: string;
  /** One line saying what this dimension is actually asking. */
  plainQuestion: string;
  /** Notion column this dimension is written to. */
  column: string;
  /** The scoring instruction given to the model. */
  question: string;
}

/** The score at or above which a dimension counts as done well. */
export const GOOD_SCORE = 7;

export const DIMENSIONS: Dimension[] = [
${entries}
];

export const RUBRIC_VERSION = ${JSON.stringify(r.version)};

/**
 * How many dimensions must be scored before a call has an overall at all.
 * Below it the dimension scores stand on their own and the call has no place
 * on any average — a 17-minute payment call scored on two dimensions was the
 * joint top call on the board before this existed.
 */
export const MIN_SCORED_DIMENSIONS = ${JSON.stringify(r.minScoredDimensions)};

/** Verdict bands, highest threshold first. */
export const VERDICTS: { min: number; label: string }[] = [
${verdicts}
];

export function verdictFor(overall: number): string {
  return VERDICTS.find((v) => overall >= v.min)?.label ?? VERDICTS[VERDICTS.length - 1].label;
}
`;
}

function buildLeadQualityModule(r) {
  const lq = r.leadQuality;

  const factors = lq.factors
    .map(
      (f) =>
        `  {\n    key: "${f.key}",\n    name: ${JSON.stringify(f.name)},\n` +
        `    column: ${JSON.stringify(f.column)},\n` +
        `    max: ${f.max},\n` +
        `    belief: ${f.belief == null ? "null" : JSON.stringify(f.belief)},\n` +
        `    question: ${JSON.stringify(f.question)},\n  },`
    )
    .join("\n");

  const bands = lq.bands
    .map((b) => `  { min: ${b.min}, label: ${JSON.stringify(b.label)} },`)
    .join("\n");

  const objections = r.objections.types
    .map(
      (t) =>
        `  {\n    name: ${JSON.stringify(t.name)},\n` +
        `    belief: ${t.belief == null ? "null" : JSON.stringify(t.belief)},\n` +
        `    detail: ${JSON.stringify(t.detail)},\n  },`
    )
    .join("\n");

  return `// ${GENERATED_BY}

export type LeadFactorKey =
${lq.factors.map((f) => `  | "${f.key}"`).join("\n")};

export interface LeadFactor {
  /** Field name in the scorer's output and on the CallRecord. */
  key: LeadFactorKey;
  /** Shown in the dashboard, and the Notion column name. */
  name: string;
  /** Notion column this factor is written to. */
  column: string;
  /** This factor's own ceiling. They differ, and they sum to LEAD_MAX. */
  max: number;
  /** The buying belief this factor measures, or null for fit. */
  belief: string | null;
  /** The scoring instruction given to the model. */
  question: string;
}

export const LEAD_FACTORS: LeadFactor[] = [
${factors}
];

/** What a lead scores when every factor is scored at its ceiling. */
export const LEAD_MAX = ${lq.max};

/**
 * Below this many scored factors, a Lead Score is not worth showing. A call
 * that ended in the first two minutes can produce two confident factors, and
 * scaling those two up to a number out of ${lq.max} would read as a verdict on
 * a lead nobody actually assessed.
 */
export const MIN_SCORED_FACTORS = 4;

/** Lead quality bands, highest threshold first. */
export const LEAD_BANDS: { min: number; label: string }[] = [
${bands}
];

/**
 * The two thresholds the bands turn on, read off the bands themselves.
 *
 * Both numbers used to be typed again wherever a lead score was coloured — 75
 * and 55 as bare literals in the call table and the scorecard — so a band could
 * be renamed or moved here and the colours would keep the old split with
 * nothing to show for it.
 *
 * EMITTED BY THE GENERATOR, not written into the file afterwards. It was added
 * to src/lib/lead-quality.ts by hand, which that file's own header forbids, so
 * the next build deleted all three and took three tests with it — silently, in
 * a run whose visible purpose was something else entirely. A generated file is
 * only as safe as its generator.
 */
function bandMin(label: string): number {
  const band = LEAD_BANDS.find((b) => b.label === label);
  if (!band) throw new Error(\`No lead band called "\${label}"\`);
  return band.min;
}

/** At or above this, a lead is Strong. */
export const GOOD_LEAD_SCORE = bandMin("Strong");

/** At or above this but below GOOD_LEAD_SCORE, a lead is Moderate. */
export const FAIR_LEAD_SCORE = bandMin("Moderate");

export function leadBandFor(score: number): string {
  return LEAD_BANDS.find((b) => score >= b.min)?.label ?? LEAD_BANDS[LEAD_BANDS.length - 1].label;
}

/**
 * A lead's score out of ${lq.max}, normalised over the factors that were
 * actually scored. Scoring six of eight factors gives a score out of the six
 * maximums scaled to ${lq.max}, so a call that never reached the money question
 * is not punished for it — but with fewer than MIN_SCORED_FACTORS behind it,
 * there is no score at all.
 */
export function leadScore(
  scores: Record<LeadFactorKey, number | null>
): number | null {
  const scored = LEAD_FACTORS.filter((f) => scores[f.key] != null);
  if (scored.length < MIN_SCORED_FACTORS) return null;
  const got = scored.reduce((sum, f) => sum + (scores[f.key] as number), 0);
  const possible = scored.reduce((sum, f) => sum + f.max, 0);
  return Math.round((got / possible) * LEAD_MAX);
}

export interface ObjectionType {
  name: string;
  /** The buying belief the objection points at, or null. */
  belief: string | null;
  detail: string;
}

export const OBJECTION_TYPES: ObjectionType[] = [
${objections}
];

/** The entry that means no objection was voiced, excluded from frequency counts. */
export const NO_OBJECTION = ${JSON.stringify(
    r.objections.types[r.objections.types.length - 1].name
  )};

export const OBJECTIONS_COLUMN = ${JSON.stringify(r.objections.column)};
export const PRIMARY_OBJECTION_COLUMN = ${JSON.stringify(r.objections.primaryColumn)};
export const LEAD_SCORE_COLUMN = ${JSON.stringify(lq.column)};
export const LEAD_READ_COLUMN = ${JSON.stringify(lq.readColumn)};
`;
}

/* ---------------------------------------------------------------- workflow */

function buildWorkflow(r, systemPrompt, schema) {
  const template = JSON.parse(read("automation/sales-call-tracker.template.json"));
  const node = template.nodes.find((n) => n.name === "Load Rubric");
  if (!node) throw new Error("template is missing the 'Load Rubric' node");

  const assign = (name, value) => {
    const a = node.parameters.assignments.assignments.find((x) => x.name === name);
    if (!a) throw new Error(`'Load Rubric' is missing the '${name}' assignment`);
    a.value = value;
  };

  assign("system_prompt", systemPrompt);
  // Carried as a JSON string, not an n8n object assignment: the HTTP node
  // parses it back with JSON.parse. Keeping it a string avoids n8n coercing a
  // deeply nested schema on the way through.
  assign("output_schema", JSON.stringify(schema));
  assign("rubric_version", r.version);
  // The verdict bands and the overall floor travel with the prompt so the
  // Notion write reads them from the same box the rubric came from, instead of
  // keeping a typed-out copy of the thresholds that drifts from rubric.json.
  assign("verdicts", JSON.stringify(r.verdicts));
  assign("min_scored_dimensions", r.minScoredDimensions);

  return template;
}

