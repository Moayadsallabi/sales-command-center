/* QUOTING THE PROSPECT IS WHAT BROKE THE TRACKER ON 2026-08-19.

   Every reasoning field asks the model to quote the transcript, and a quoted
   phrase inside a JSON string value needs escaped double quotes. On Mason's
   call the model got stuck emitting that escape sequence: 26,626 characters of
   the same two bytes, 73% of the whole response, running straight into the
   token ceiling. The scorecard was never closed, and the first 9,950
   characters \u2014 a complete, correct scoring of the call \u2014 were thrown away.

   THE SCHEMA CANNOT PREVENT THIS. The obvious fix is a maxLength on the free
   text fields, and it is not available: Anthropic's structured-output JSON
   Schema subset does not support maxLength or minLength, and this workflow
   posts raw JSON rather than going through an SDK that would quietly strip an
   unsupported keyword. Checked against the API reference before writing a cap
   that would have been rejected on every call.

   So prompting is the lever. The rule does NOT live in this generated prompt,
   though: each client's live prompt is produced once by configure-client.mjs
   with their own offer context and then edited in n8n, so a rule added here
   reaches new clients only. It goes in the request body in the workflow
   template instead, where it is appended to whatever system prompt that client
   is running. Client-agnostic craft guidance, one home, every client. */
function buildSystemPrompt(r) {
  const out = [];

  out.push(
    "You are a sales call reviewer. You read the transcript of a single sales call and return a structured scorecard of that call.",
    "",
    "You are reviewing the person who was selling — referred to below as the caller. You are not reviewing the prospect.",
    "",
    "## The offer being sold",
    "",
    r.offerContextPlaceholder,
    "",
    "## How to score",
    ""
  );

  for (const p of r.scoringPrinciples) out.push(`- ${p}`);

  if (r.offerMatch) {
    out.push(
      "",
      `## ${r.offerMatch.heading}`,
      ""
    );
    for (const w of r.offerMatch.why) out.push(w, "");
    for (const i of r.offerMatch.instruction) out.push(`- ${i}`);
  }

  out.push(
    "",
    `## The ${numberWord(r.dimensions.length)} dimensions`,
    "",
    "Score each dimension from 1 to 10 and write a two-to-four sentence breakdown explaining the score with specific reference to the transcript.",
    ""
  );

  r.dimensions.forEach((d, i) => {
    out.push(`### ${i + 1}. ${d.name}`, "", d.question, "", d.detail, "", "Scoring bands:");
    for (const b of d.bands) out.push(`- ${b.range}: ${b.text}`);
    out.push("", "Look for:");
    for (const f of d.flags) out.push(`- ${f}`);
    out.push("");
  });

  out.push(...leadQualitySection(r, "key"));
  out.push(...objectionsSection(r));

  out.push("## Bonus flags", "");
  for (const f of r.bonusFlags) {
    const opts =
      f.type === "enum" ? ` Answer with one of: ${f.options.join(", ")}.` : "";
    out.push(`- **${f.key}** — ${f.question}${opts}`);
  }

  out.push("", "## Written feedback", "");
  for (const n of r.narrative) out.push(`- **${n.key}** — ${n.instruction}`);

  out.push(
    "",
    "## Commercial fields",
    "",
    `Also extract the commercial facts of the call. Outcome definitions: ${r.commercial.outcomeGuide}`,
    "",
    "For any commercial field the transcript does not establish, return null rather than guessing. `lead_source` cannot be null: when the transcript never establishes where the prospect came from, answer Unknown rather than guessing.",
    "",
    // THE TWO PRICE FIELDS WERE THE ONLY MONEY FIELDS NEVER DEFINED. Every
    // other one below is spelled out, and these two were left to a pair of
    // near-identical names. The model filled both with the number that was
    // quoted, so calls recorded as "No deal" arrived carrying a closed price —
    // 1,500 discussed, refused, and written down as 1,500 closed. It was not
    // inventing a sale; nothing ever told it the second field means money the
    // prospect agreed to hand over.
    /* THE PRICE RULE MOVED TO THE REQUEST BODY (2026-08-19).
       A rule written here reaches only clients configured AFTER it lands: a
       client's prompt is generated once with their own offer context and then
       lives in n8n, where this file cannot touch it. Brey's live prompt was
       built before this paragraph existed and never got it, so his scorecards
       have been recording a price that was named and refused as a price
       closed. Rules that must reach already-deployed clients ride the request
       body in the workflow template instead — see 'Writing the quotes'. */
    "",
    "`collected_on_call` is money that actually changed hands **during the call** — a card taken while the prospect was still on the line. A deal that was agreed on the call but paid afterwards collected nothing on the call, so it is 0, not the price. Payments that land later are recorded by hand afterwards and are not your job to predict.",
    "",
    `\`currency\` is the currency the price was quoted in, one of ${r.commercial.currencies.join(", ")}. Take it from how the caller said the number — "three thousand euros" or "€3,000" is EUR, "$6,000" is USD. When no currency is stated anywhere in the call, answer ${r.commercial.defaultCurrency}. Every money field you return must be in that one currency; never convert.`,
    "",
    "`summary` is two to three sentences on what happened, written for someone who did not attend the call."
  );

  return out.join("\n") + "\n";
}

function numberWord(n) {
  return (
    ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten"][n] ??
    String(n)
  );
}

