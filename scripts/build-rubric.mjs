// The lead-quality rubric, rendered once and reused by the system prompt and
// the chat skill so a manual review scores a lead exactly as the workflow does.
// `label` picks what each factor is called in the output the reader must
// produce: the prompt asks for JSON keys, the skill asks for readable names.
function leadQualitySection(r, label) {
  const lq = r.leadQuality;
  const out = [
    "",
    `## Lead quality — ${numberWord(lq.factors.length)} factors, scored out of ${lq.max}`,
    "",
    lq.intro,
    "",
    `Each factor is scored from 1 to its own maximum — a number only, with no written reason of its own. The factors carry different maximums because they do not matter equally: they sum to ${lq.max} when every one is scored. Your reading of the lead as a whole goes in lead_read, and that is where the evidence for these numbers belongs.`,
    "",
  ];

  for (const f of lq.factors) {
    const belief = f.belief ? ` · maps to the ${f.belief} belief` : "";
    out.push(
      `### ${label === "key" ? f.key : f.name} — out of ${f.max}${belief}`,
      "",
      f.question,
      "",
      f.detail,
      "",
      "Scoring bands:"
    );
    for (const b of f.bands) out.push(`- ${b.range}: ${b.text}`);
    out.push("");
  }

  out.push(
    "Patterns worth naming when you see them:",
    ...lq.patterns.map((p) => `- ${p}`),
    ""
  );

  return out;
}

function objectionsSection(r) {
  const o = r.objections;
  const out = ["", "## Objections raised", "", o.intro, ""];
  for (const t of o.types) {
    const belief = t.belief ? ` (${t.belief})` : "";
    out.push(`- **${t.name}**${belief} — ${t.detail}`);
  }
  out.push(
    "",
    "List every objection the prospect actually voiced. Then name the single one that decided the call — the one that, left unresolved, is why it did not close. When the call closed, or no objection was raised, the primary objection is null.",
    ""
  );
  return out;
}

/* ------------------------------------------------------------------ schema */

// Structured outputs reject `minimum`/`maximum`, so a bounded integer is
// expressed as an enum of its allowed values.
//
// 0 is the "no evidence" value, and it is in the enum rather than expressed as
// `null` because the API caps a schema at 16 union-typed parameters and every
// nullable field spends one. With sixteen scores plus the commercial fields,
// nullable scores put this schema at 25 and every request was refused outright
// with a 400 — silently, since nothing validates the schema until a real call
// reaches the model. Scores run from 1, so 0 cannot collide with a real one.
// It is translated back to an empty cell at the Notion write, which is the only
// place that has to know: everything downstream still reads a blank score as
// "not assessed" exactly as before.
// Two separate limits bite here, and the second only becomes visible once the
// first is satisfied. Beyond the 16-union cap, the API also refuses a schema
// whose compiled grammar is "too large" — and sixteen score fields expressed as
// enums of their allowed values were 80% of that grammar (196 of 244
// alternatives). So a score is a plain integer: the range is stated in each
// description and clamped again when the row is written, rather than enforced
// by the schema. `minimum`/`maximum` are not an option — structured outputs
// reject them.
const NO_EVIDENCE = 0;
const SCORE_MAX = 10;

/** How many union-typed parameters the API will accept in one schema. */
const UNION_LIMIT = 16;

const nullable = (schema) => ({ anyOf: [schema, { type: "null" }] });

/** Every parameter in the schema expressed as a union, at any depth. */
function countUnions(node) {
  let count = 0;
  if (node && typeof node === "object") {
    for (const value of Object.values(node.properties ?? {})) {
      if (Array.isArray(value.type) || "anyOf" in value || "oneOf" in value) count++;
      count += countUnions(value);
    }
    if (node.items && typeof node.items === "object") count += countUnions(node.items);
  }
  return count;
}

function obj(properties) {
  return {
    type: "object",
    properties,
    required: Object.keys(properties),
    additionalProperties: false,
  };
}

function buildOutputSchema(r) {
  const scores = {};
  for (const d of r.dimensions) {
    scores[d.key] = obj({
      // 0 means "no evidence", so a dimension the call never reached is
      // recorded as unjudged instead of a guessed middle score that pollutes
      // averages. See NO_EVIDENCE for why this is not `null`.
      score: {
        // A bare integer, not an enum of the allowed values. Sixteen score
        // enums were 80% of the compiled grammar and the API refused it as
        // "too large" — see SCORE_MAX. The range lives in the description and
        // is clamped again at the Notion write.
        type: "integer",
        description: `${d.question} A whole number from 1 to ${SCORE_MAX}, or ${NO_EVIDENCE} when the transcript gives no evidence to judge this.`,
      },
      reasoning: {
        type: "string",
        description: `Two to four sentences justifying the ${d.name} score, quoting the transcript. When the score is ${NO_EVIDENCE}, say what evidence was missing.`,
      },
    });
  }

  // Each lead factor has its own maximum, so each gets its own enum. 0 carries
  // the same meaning it does on the dimensions: a factor the call never reached
  // is recorded as no evidence, and the Lead Score is then averaged over the
  // factors that do have one rather than over a set padded with guesses.
  // Each factor is a bare number, not an object with its own written reason.
  // The API refuses a schema whose compiled grammar is too large, and that is
  // driven by the count of fields and nested sections rather than by enums:
  // eight factor objects with a reason each were 24 fields and 9 sections of a
  // schema that would not compile at 77 and 22. The per-factor reasons were
  // rendered only as bullets on the Notion page and read by nothing else —
  // `lead_read` already carries the reading of the lead as a whole.
  const leadFactors = {};
  for (const f of r.leadQuality.factors) {
    leadFactors[f.key] = {
      type: "integer",
      description: `${f.question} A whole number from 1 to ${f.max}, or ${NO_EVIDENCE} when the call never produced evidence either way.`,
    };
  }

  const objectionNames = r.objections.types.map((t) => t.name);

  const flags = {};
  for (const f of r.bonusFlags) {
    flags[f.key] =
      f.type === "enum"
        ? { type: "string", enum: f.options, description: f.question }
        : { type: "boolean", description: f.question };
  }

  const narrative = {};
  for (const n of r.narrative) {
    narrative[n.key] = { type: "string", description: n.instruction };
  }

  // `tier` only exists for a client whose offers actually come in tiers. With
  // none configured the field is left out of the schema altogether rather than
  // shipped as an always-null column: asking a model to fill in a band nobody
  // has defined produces a confident guess, which is what it did on Brey's
  // tracker for months. Put the numbers back in `commercial.tiers` and write
  // down what they mean, and it returns.
  const schema = obj({
    outcome: { type: "string", enum: r.commercial.outcomes },
    // Whose product was sold. Every other field on this row describes HOW the
    // call went; this one answers whether the call was ours to count at all,
    // and nothing else on the row can distinguish it.
    // Deliberately TWO FLAT FIELDS, not one nested object. Anthropic compiles
    // this schema into a validator before it will run the request, and that
    // validator has a size ceiling that nested objects spend far faster than
    // fields do. Measured against the live API at this workflow's own settings
    // (adaptive thinking, effort high) on 2026-08-25: the schema without these
    // two fields compiles, the schema plus these two flat fields compiles, and
    // the schema plus the same pair wrapped in ONE object does not — it returns
    // 400 "The compiled grammar is too large". Grouping other fields, shrinking
    // the enums and changing how nulls are written all still failed, so the
    // ceiling is about nesting, not field count. Nesting these again silently
    // stops every call being scored.
    ...(r.offerMatch
      ? {
          offer_match: {
            type: "string",
            enum: r.offerMatch.verdicts,
            description:
              `${r.offerMatch.heading} Answer "${r.offerMatch.verdicts[1]}" only when the transcript ` +
              `positively identifies a different product. Answer "${r.offerMatch.default}" whenever you cannot tell.`,
          },
          offer_evidence: {
            type: "string",
            description:
              "The line from the transcript that decides it, with its [mm:ss]. " +
              "When the verdict is unclear, say what was missing instead.",
          },
        }
      : {}),
    ...(r.commercial.tiers.length
      ? { tier: nullable({ type: "integer", enum: r.commercial.tiers }) }
      : {}),
    price_discussed: nullable({ type: "number" }),
    price_closed: nullable({ type: "number" }),
    collected_on_call: nullable({ type: "number" }),
    // Which currency the three amounts above are in. Never converted here —
    // the dashboard applies the row's FX Rate when it totals across calls.
    currency: { type: "string", enum: r.commercial.currencies },
    payment_structure: nullable({
      type: "string",
      enum: r.commercial.paymentStructures,
    }),
    prospect_revenue: nullable({ type: "string" }),
    niche: nullable({ type: "string" }),
    location: nullable({ type: "string" }),
    lead_source: { type: "string", enum: r.commercial.leadSources },
    summary: { type: "string" },
    scores: obj(scores),
    lead_quality: obj(leadFactors),
    objections: obj({
      raised: {
        type: "array",
        items: { type: "string", enum: objectionNames },
        description:
          "Every objection the prospect voiced, whether or not it was resolved. Use the single entry None raised when none was.",
      },
      primary: {
        anyOf: [{ type: "string", enum: objectionNames }, { type: "null" }],
        description:
          "The one objection that decided the call. Null when the call closed or no objection was raised.",
      },
      detail: {
        type: "string",
        description:
          "One or two sentences per objection raised: the prospect's own words with its [mm:ss], and whether the caller resolved it. Empty string when none was raised.",
      },
    }),
    flags: obj(flags),
    narrative: obj(narrative),
  });

  // The API refuses a schema with more than UNION_LIMIT union-typed parameters
  // and refuses it at request time, not at build time — so without this check
  // the failure surfaces as a 400 on a live call, days after the rubric shipped,
  // with nothing in the repo looking wrong. Rubric v1.5.0 sat live and scored
  // nothing for a day exactly this way. Fail the build instead.
  const unions = countUnions(schema);
  if (unions > UNION_LIMIT) {
    throw new Error(
      `Output schema has ${unions} union-typed parameters; the API accepts ${UNION_LIMIT}.\n` +
        `  Every nullable field spends one. Express "absent" without a union — a\n` +
        `  sentinel inside the enum, as the scores do with ${NO_EVIDENCE} — or drop a field.`
    );
  }

  return schema;
}

/* ---------------------------------------------------------------- markdown */

function buildMarkdown(r) {
  const out = [`# ${r.title}`, "", `_${r.subtitle}_`, "", `<!-- ${GENERATED_BY} -->`, ""];

  out.push("## How scoring works", "");
  for (const p of r.scoringPrinciples) out.push(`- ${p}`);

  out.push("", "The overall score is the plain average of the eight dimensions.", "", "| Overall | Verdict |", "| --- | --- |");
  r.verdicts.forEach((v, i) => {
    const range =
      i === 0
        ? `${v.min.toFixed(1)}–10`
        : `${v.min.toFixed(1)}–${(r.verdicts[i - 1].min - 0.1).toFixed(1)}`;
    out.push(`| ${range} | ${v.label} |`);
  });

  out.push("", "## The dimensions", "");
  r.dimensions.forEach((d, i) => {
    out.push(`### ${i + 1}. ${d.name}`, "", `**${d.question}**`, "", d.detail, "");
    out.push("| Score | What it looks like |", "| --- | --- |");
    for (const b of d.bands) out.push(`| ${b.range} | ${b.text} |`);
    out.push("", "What the scorer looks for:", "");
    for (const f of d.flags) out.push(`- ${f}`);
    out.push("");
  });

  const lq = r.leadQuality;
  out.push(`## Lead quality`, "", lq.intro, "");
  out.push(
    `Scored out of ${lq.max}, separately from the caller. The maximums differ because the factors do not matter equally.`,
    "",
    "| Factor | Out of | Belief | What it asks |",
    "| --- | --- | --- | --- |"
  );
  for (const f of lq.factors) {
    out.push(`| ${f.name} | ${f.max} | ${f.belief ?? "—"} | ${f.question} |`);
  }
  out.push("", "| Lead Score | Reads as |", "| --- | --- |");
  lq.bands.forEach((b, i) => {
    const range =
      i === 0 ? `${b.min}–${lq.max}` : `${b.min}–${lq.bands[i - 1].min - 1}`;
    out.push(`| ${range} | ${b.label} |`);
  });

  out.push("", "### The factors in full", "");
  lq.factors.forEach((f) => {
    out.push(`#### ${f.name} — out of ${f.max}`, "", `**${f.question}**`, "", f.detail, "");
    out.push("| Score | What it looks like |", "| --- | --- |");
    for (const b of f.bands) out.push(`| ${b.range} | ${b.text} |`);
    out.push("");
  });

  out.push("### Patterns", "");
  for (const p of lq.patterns) out.push(`- ${p}`);

  out.push("", "## Objections", "", r.objections.intro, "");
  out.push("| Objection | Belief behind it | What counts |", "| --- | --- | --- |");
  for (const t of r.objections.types) {
    out.push(`| ${t.name} | ${t.belief ?? "—"} | ${t.detail} |`);
  }

  out.push("", "## Bonus flags", "", "| Flag | Question |", "| --- | --- |");
  for (const f of r.bonusFlags) out.push(`| ${f.column} | ${f.question} |`);

  out.push("", "## Written feedback", "", "Every review also produces:", "");
  for (const n of r.narrative) out.push(`- **${n.heading}** — ${n.instruction}`);

  out.push("");
  return out.join("\n");
}

